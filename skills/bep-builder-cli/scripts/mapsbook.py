"""Build the BEP process-map workbook (Uses, Exchanges, Summary, Keywords, Read Me).

Called by `bep.py maps-workbook`. Needs openpyxl. The workbook is the editable side of a
round trip: edit it in Excel or Apple Numbers, then `bep.py apply-maps` reads it back.
"""
import sys

import processmap
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.worksheet.datavalidation import DataValidation
from openpyxl.comments import Comment


def build(plans, out):
    """plans: list of (project name, plan dict). Writes the workbook to `out`."""
    bep = sys.modules.get("__main__") if hasattr(sys.modules.get("__main__"), "exchange_feeds") else __import__("bep")
    F = "Arial"
    HEAD = Font(name=F, bold=True, color="FFFFFF"); HEAD_FILL = PatternFill("solid", fgColor="16212A")
    BODY = Font(name=F, size=10); INPUT = Font(name=F, size=10, color="0000FF"); LINK = Font(name=F, size=10, color="008000")
    YELLOW = PatternFill("solid", fgColor="FFF2B3"); GREY = PatternFill("solid", fgColor="EEF2F1")
    THIN = Border(bottom=Side(style="thin", color="D3DBD9"))
    WRAP = Alignment(wrap_text=True, vertical="top")

    def header(ws, cols, widths):
        for i, (c, w) in enumerate(zip(cols, widths), 1):
            cell = ws.cell(row=1, column=i, value=c); cell.font = HEAD; cell.fill = HEAD_FILL; cell.alignment = Alignment(vertical="center", wrap_text=True)
            ws.column_dimensions[cell.column_letter].width = w
        ws.row_dimensions[1].height = 30; ws.freeze_panes = "A2"

    def style_row(ws, r, ncols, inputs=()):
        for c in range(1, ncols + 1):
            cell = ws.cell(row=r, column=c); cell.border = THIN; cell.alignment = WRAP
            if c in inputs: cell.font = INPUT; cell.fill = YELLOW
            elif cell.font != LINK: cell.font = BODY

    wb = Workbook()
    # ---------------- Read Me
    rm = wb.active; rm.title = "Read Me"
    rm.column_dimensions["A"].width = 100
    lines = [
        ("BEP process maps — data behind the Level 1 process maps (BEP section 05)", Font(name=F, size=14, bold=True)),
        ("", BODY),
        ("What this workbook is", Font(name=F, bold=True)),
        ("Each process map is drawn from two lists in a BEP plan: the BIM uses the team selected, and the information exchanges between parties. This workbook holds those lists for every project so the team can review and plan the maps together.", BODY),
        ("", BODY),
        ("How to edit", Font(name=F, bold=True)),
        ("• Yellow cells with blue text are inputs. Change them; everything else is calculated.", BODY),
        ("• Uses tab: set Selected to Y or N and name the Responsible party. The Map role column shows which use leads each phase (it receives the arrow from the previous phase).", BODY),
        ("• Exchanges tab: one row per exchange. Pick the use it feeds from the dropdown; On map? shows whether it will appear on the map.", BODY),
        ("• To add a project, copy its 12 rows in Uses and add its exchanges with the same Project name. Summary counts update automatically once you add the project name there.", BODY),
        ("", BODY),
        ("How the maps are drawn", Font(name=F, bold=True)),
        ("Columns are phases (Planning, Design, Construction, Operations). Each selected use is a box in its phase. Exchanges label the arrow into the use they feed. Phases with no selected use get a grey placeholder box so work never jumps from design straight to operations.", BODY),
        ("The bep CLI matches exchanges to uses by keyword (see the Keywords tab). The 'Feeds use' column here starts with that match; naming an exchange after what it feeds keeps the CLI and this sheet in agreement.", BODY),
        ("", BODY),
        ("Sources of the data", Font(name=F, bold=True)),
        ("Each project's rows come from its BEP plan file, generated by bep.py maps-workbook. Blank cells were not yet answered in the plan. Projects named EXAMPLE are illustrative.", BODY),
        ("To bring edits back into a plan: bep.py apply-maps PLAN this-file --project \"Project name\".", BODY),
        ("COBie rows marked 'added: COBie handover required' are added automatically when a plan requires COBie and lists no COBie exchange.", BODY),
    ]
    for i, (t, f) in enumerate(lines, 1):
        c = rm.cell(row=i, column=1, value=t); c.font = f; c.alignment = Alignment(wrap_text=True, vertical="top")

    # ---------------- Uses
    us = wb.create_sheet("Uses")
    cols = ["Project", "Phase", "BIM use", "Use ID", "Selected (Y/N)", "Responsible", "Map role"]
    header(us, cols, [34, 14, 34, 11, 13, 30, 16])
    r = 2
    for name, p in plans:
        for uid, uname, uphase in bep.USES:
            ph = processmap._phase_of(uphase)
            u = p["uses"][uid]
            vals = [name, ph, uname, uid, "Y" if u["on"] else "N", u.get("party", "")]
            for c, v in enumerate(vals, 1): us.cell(row=r, column=c, value=v)
            us.cell(row=r, column=7, value=f'=IF(E{r}<>"Y","—",IF(COUNTIFS(A$2:A{r},A{r},B$2:B{r},B{r},E$2:E{r},"Y")=1,"Phase lead","Box"))')
            style_row(us, r, 7, inputs=(5, 6)); r += 1
    uses_last = r - 1
    # order rows so phase order is respected within each project? catalog order already Planning→Design→...→Operations except 'ifc' (All→Design) after 4d (Construction).
    dv = DataValidation(type="list", formula1='"Y,N"', allow_blank=False); us.add_data_validation(dv); dv.add(f"E2:E{uses_last}")
    us.cell(row=1, column=7).comment = Comment("Phase lead = first selected use in its phase (top to bottom). It receives the arrow from the previous phase and feeds the other uses in its phase.", "BEP Builder")

    # ---------------- Exchanges
    ex = wb.create_sheet("Exchanges")
    cols = ["Project", "Exchange", "From", "To", "Model content", "LOD", "Due", "Feeds use", "Arrow label", "On map?", "Note"]
    header(ex, cols, [34, 26, 18, 18, 30, 13, 18, 30, 44, 22, 28])
    use_names = [u[1] for u in bep.USES]
    r = 2
    for name, p in plans:
        model = processmap.build(p, bep.USES)
        rows = [dict(e) for e in p["exchanges"] if e.get("what", "").strip()]
        added = False
        if p.get("cobie") and p["uses"]["cobie"]["on"] and not any("cobie" in e["what"].lower() for e in rows):
            rows.append({"what": "COBie handover", "from": "", "to": "", "content": "", "lod": "", "due": ""}); added = True
        for e in rows:
            fid = bep.exchange_feeds(p, e)
            feeds = dict((u[0], u[1]) for u in bep.USES).get(fid, "")
            vals = [name, e["what"], e.get("from", ""), e.get("to", ""), e.get("content", ""), e.get("lod", ""), e.get("due", ""), feeds]
            for c, v in enumerate(vals, 1): ex.cell(row=r, column=c, value=v)
            ex.cell(row=r, column=9, value=f'=B{r}&IF(F{r}<>""," · "&F{r},"")&IF(G{r}<>""," · "&G{r},"")')
            ex.cell(row=r, column=10, value=f'=IF(H{r}="","No — pick the use it feeds",IF(COUNTIFS(Uses!$A$2:$A${uses_last},A{r},Uses!$C$2:$C${uses_last},H{r},Uses!$E$2:$E${uses_last},"Y")>0,"Yes","No — that use isn\'t selected"))')
            if added and e["what"] == "COBie handover" and not e.get("from"):
                ex.cell(row=r, column=11, value="added: COBie handover required")
            style_row(ex, r, 11, inputs=(2, 3, 4, 5, 6, 7, 8))
            ex.cell(row=r, column=10).font = LINK; r += 1
    # spare input rows
    for k in range(3):
        style_row(ex, r + k, 11, inputs=(1, 2, 3, 4, 5, 6, 7, 8))
        ex.cell(row=r + k, column=9, value=f'=IF(B{r+k}="","",B{r+k}&IF(F{r+k}<>""," · "&F{r+k},"")&IF(G{r+k}<>""," · "&G{r+k},""))')
        ex.cell(row=r + k, column=10, value=f'=IF(B{r+k}="","",IF(H{r+k}="","No — pick the use it feeds",IF(COUNTIFS(Uses!$A$2:$A${uses_last},A{r+k},Uses!$C$2:$C${uses_last},H{r+k},Uses!$E$2:$E${uses_last},"Y")>0,"Yes","No — that use isn\'t selected")))')
        ex.cell(row=r + k, column=10).font = LINK
    ex_last = r + 2
    ex.cell(row=ex_last + 2, column=1, value="Blank yellow rows above are for new exchanges.").font = Font(name=F, size=9, italic=True)
    dv2 = DataValidation(type="list", formula1='"' + ",".join(n.replace(",", "") for n in use_names) + '"', allow_blank=True)
    ex.add_data_validation(dv2); dv2.add(f"H2:H{ex_last}")
    dv3 = DataValidation(type="list", formula1='"LOD 100,LOD 200,LOD 300,LOD 350,LOD 400,LOD 500 data"', allow_blank=True)
    ex.add_data_validation(dv3); dv3.add(f"F2:F{ex_last}")
    ex.cell(row=1, column=10).comment = Comment("Green = calculated from the Uses tab. 'Yes' means the exchange labels an arrow on the map.", "BEP Builder")

    # ---------------- Summary
    sm = wb.create_sheet("Summary", 1)
    cols = ["Project", "Uses selected", "Phases with a use", "Placeholder boxes", "Exchanges", "Exchanges on map", "Not on map"]
    header(sm, cols, [36, 14, 16, 16, 12, 16, 12])
    PH = ["Planning", "Design", "Construction", "Operations"]
    U = f"Uses!$A$2:$A${uses_last}"; UB = f"Uses!$B$2:$B${uses_last}"; UE = f"Uses!$E$2:$E${uses_last}"
    EA = f"Exchanges!$A$2:$A${ex_last}"; EJ = f"Exchanges!$J$2:$J${ex_last}"
    for i, (name, _) in enumerate(plans, 2):
        sm.cell(row=i, column=1, value=name)
        sm.cell(row=i, column=2, value=f'=COUNTIFS({U},A{i},{UE},"Y")')
        sm.cell(row=i, column=3, value="=" + "+".join(f'(COUNTIFS({U},$A{i},{UB},"{ph}",{UE},"Y")>0)' for ph in PH))
        # placeholders: phases between first and last used phase with no use. Planning always has the requirements box, so first = Planning.
        used = [f'(COUNTIFS({U},$A{i},{UB},"{ph}",{UE},"Y")>0)' for ph in PH]
        sm.cell(row=i, column=4, value=f'=IF({used[3]},({used[1]}=FALSE)+({used[2]}=FALSE),IF({used[2]},({used[1]}=FALSE),0))')
        sm.cell(row=i, column=5, value=f'=COUNTIFS({EA},A{i})')
        sm.cell(row=i, column=6, value=f'=COUNTIFS({EA},A{i},{EJ},"Yes")')
        sm.cell(row=i, column=7, value=f'=E{i}-F{i}')
        style_row(sm, i, 7)
    n = len(plans) + 1
    sm.cell(row=n + 2, column=1, value="Planning always has the 'Owner requirements & goals' box, so it never needs a placeholder.").font = Font(name=F, size=9, italic=True)

    # ---------------- Keywords
    kw = wb.create_sheet("Keywords")
    header(kw, ["BIM use", "Use ID", "Phase on map", "Exchange names containing any of these words feed this use"], [34, 11, 16, 70])
    for r, (uid, uname, uphase) in enumerate(bep.USES, 2):
        for c, v in enumerate([uname, uid, processmap._phase_of(uphase), ", ".join(processmap.USE_KEYWORDS.get(uid, []))], 1):
            kw.cell(row=r, column=c, value=v)
        style_row(kw, r, 4)
    kw.cell(row=len(bep.USES) + 3, column=1, value="Matching runs top to bottom; the first selected use whose words appear in the exchange name or content wins.").font = Font(name=F, size=9, italic=True)

    wb.save(out)
    return out
